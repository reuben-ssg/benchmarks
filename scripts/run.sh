#!/bin/bash
# Times every tool on every case, interleaved in one hyperfine run per size so background noise hits them equally.
# Waits for a quiet machine before each size: on macOS, AC power and a 1-minute load under $MAX_LOAD;
# on Linux, only the load. QUIET=0 skips the wait (CI runners can't be made quiet).
#
# Eleventy, Astro, Starlight, Jekyll and mdBook are optional: a missing one is skipped with a message.
# REQUIRE_TOOLS=1 (CI) turns a missing one into an error, listing every missing tool at once.
#
# Usage: REUBEN=/path/to/reuben [BASELINE=/path/to/older/reuben] [HASH_CASE=1] [QUIET=0] scripts/run.sh [sizes...]
# Results: results/latest/<size>.{json,txt}, conditions-<size>.txt and table.md.
set -euo pipefail
B=$(cd "$(dirname "$0")/.." && pwd)
cd "$B"
. scripts/tools.sh
: "${REUBEN:?set REUBEN to the reuben binary to measure}"
if [ "${REQUIRE_TOOLS:-0}" = 1 ]; then
  missing=0
  for t in eleventy astro starlight jekyll mdbook; do
    if ! "have_$t"; then echo "error: $t is not installed (REQUIRE_TOOLS=1)"; missing=1; fi
  done
  [ "$missing" = 0 ] || exit 1
fi
MAX_LOAD=${MAX_LOAD:-3.5}
OUT=results/latest
HC=$B/.hugocache
# Keep the Node tools from sending telemetry during timed runs.
export ASTRO_TELEMETRY_DISABLED=1 DO_NOT_TRACK=1
rm -rf "$OUT"
mkdir -p "$OUT" "$HC"

quiet() {
  local l ac=1
  if [ "${QUIET:-1}" = 0 ]; then
    echo "quiet: check skipped (QUIET=0)"
    return
  fi
  for _ in $(seq 1 60); do
    if [ "$(uname -s)" = Darwin ]; then
      l=$(sysctl -n vm.loadavg | awk '{print $2}')
      ac=$(pmset -g batt | grep -c "AC Power" || true)
    else
      l=$(awk '{print $1}' /proc/loadavg)
    fi
    if [ "$ac" = 1 ] && awk "BEGIN{exit !($l < $MAX_LOAD)}"; then
      echo "quiet: load $l"
      return
    fi
    sleep 20
  done
  echo "WARNING: machine never got quiet (load $l, AC $ac)"
}

{
  echo "date: $(date -u +%Y-%m-%dT%H:%MZ)"
  if [ "$(uname -s)" = Darwin ]; then
    echo "machine: $(sysctl -n machdep.cpu.brand_string), $(($(sysctl -n hw.memsize) / 1073741824)) GiB, macOS $(sw_vers -productVersion)"
  else
    echo "machine: $(awk -F': ' '/^model name/ {print $2; exit}' /proc/cpuinfo), $(nproc) cores, $(awk '/^MemTotal/ {printf "%d", $2 / 1048576 + 0.5}' /proc/meminfo) GiB, $(. /etc/os-release && echo "$PRETTY_NAME")"
  fi
  [ "${GITHUB_ACTIONS:-}" = true ] && echo "runner: github-actions"
  echo "reuben: $("$REUBEN" --version)"
  [ -n "${BASELINE:-}" ] && echo "baseline: $("$BASELINE" --version)"
  echo "hugo: $(hugo version)"
  echo "zola: $(zola --version)"
  echo "hyperfine: $(hyperfine --version)"
  echo "node: $(node --version)"
  have_eleventy && echo "eleventy: $("$NODE_TOOLS/.bin/eleventy" --version)"
  have_astro && echo "astro: $("$NODE_TOOLS/.bin/astro" --version)"
  have_starlight && echo "starlight: $(node -p 'require(process.argv[1]).version' "$NODE_TOOLS/@astrojs/starlight/package.json")"
  have_jekyll && echo "jekyll: $(jekyll --version)"
  have_mdbook && echo "mdbook: $(mdbook --version)"
} > "$OUT/versions.txt"

for N in ${*:-10 50 1000 10000}; do
  quiet | tee "$OUT/conditions-$N.txt"
  runs=15
  [ "$N" -ge 10000 ] && runs=5
  c=$B/cases
  cmds=()
  [ -n "${BASELINE:-}" ] && cmds+=(-n "reuben baseline, bare" "$BASELINE build --root $c/reuben-bare-$N")
  cmds+=(
    -n "reuben, bare" "$REUBEN build --root $c/reuben-bare-$N"
    -n "reuben, bare, footnote back-links off" "$REUBEN build --root $c/reuben-bare-noback-$N"
    -n "reuben, bare + checks" "$REUBEN build --root $c/reuben-bare-checks-$N"
    -n "hugo, bare, highlighting on" "hugo --quiet --source $c/hugo-bare-$N --cacheDir $HC"
    -n "hugo, bare, highlighting off" "hugo --quiet --source $c/hugo-nohl-$N --cacheDir $HC"
    -n "zola, bare, highlighting on" "zola --root $c/zola-bare-$N build"
    -n "zola, bare, highlighting off" "zola --root $c/zola-nohl-$N build"
  )
  # Each optional tool is timed only if it is installed (and its case was generated by setup.sh).
  prep="rm -rf $c/reuben-bare-$N/dist $c/reuben-bare-noback-$N/dist $c/reuben-bare-checks-$N/dist $c/hugo-bare-$N/public $c/hugo-nohl-$N/public $c/zola-bare-$N/public $c/zola-nohl-$N/public"
  tool_case() { # have-function, label, case dir name, output folders to delete, then the command's name/command pairs
    local have=$1 label=$2 dir=$3 outs=$4
    shift 4
    if ! "$have"; then echo "skipping $label: not installed"; return; fi
    if [ ! -d "$c/$dir" ]; then echo "skipping $label: no $dir (run scripts/setup.sh $N)"; return; fi
    cmds+=("$@")
    for o in $outs; do prep="$prep $c/$dir/$o"; done
  }
  tool_case have_eleventy eleventy "eleventy-bare-$N" _site \
    -n "eleventy, bare" "$NODE_TOOLS/.bin/eleventy --quiet --config=$c/eleventy-bare-$N/eleventy.config.mjs --input=$c/eleventy-bare-$N/content --output=$c/eleventy-bare-$N/_site"
  tool_case have_astro astro "astro-bare-$N" "dist .astro node_modules/.astro" \
    -n "astro, bare, highlighting off" "$NODE_TOOLS/.bin/astro build --root $c/astro-bare-$N"
  tool_case have_starlight starlight "starlight-bare-$N" "dist .astro node_modules/.astro" \
    -n "starlight, defaults" "$NODE_TOOLS/.bin/astro build --root $c/starlight-bare-$N"
  tool_case have_jekyll jekyll "jekyll-bare-$N" _site \
    -n "jekyll, bare, highlighting off" "jekyll build --quiet --disable-disk-cache --source $c/jekyll-bare-$N --destination $c/jekyll-bare-$N/_site"
  tool_case have_mdbook mdbook "mdbook-bare-$N" book \
    -n "mdbook, bare" "mdbook build --dest-dir $c/mdbook-bare-$N/book $c/mdbook-bare-$N"
  if [ "${HASH_CASE:-0}" = 1 ]; then
    # Reuben only: older binaries reject the [assets] table.
    cmds+=(-n "reuben, bare, hashing on" "$REUBEN build --root $c/reuben-bare-hash-$N")
    prep="$prep $c/reuben-bare-hash-$N/dist"
  fi
  hyperfine -N --warmup 2 --runs "$runs" --export-json "$OUT/$N.json" \
    --prepare "$prep" \
    "${cmds[@]}" > "$OUT/$N.txt" 2>&1
  uptime >> "$OUT/conditions-$N.txt"
  # Each timed run deletes every case's output first, so build each case once more for the byte counts.
  for ((i = 2; i < ${#cmds[@]}; i += 3)); do
    eval "${cmds[$i]}" > /dev/null 2>&1 || true
  done
done

node scripts/summarize.mjs "$OUT" > "$OUT/table.md"
cat "$OUT/table.md"
